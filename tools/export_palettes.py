"""Write app/js/palettes.js from valis_fx/lib/palette.py LOOKS: every look's name, prompt words, the row it sits in, and
its grading parameters (so the studio can preview the grade live, in grade.js, on your own keyframe).

    python tools/export_palettes.py
"""
import importlib.util
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
spec = importlib.util.spec_from_file_location("palette", os.path.join(ROOT, "valis_fx", "lib", "palette.py"))
pal = importlib.util.module_from_spec(spec)
spec.loader.exec_module(pal)

GROUPS = [
    ("Film stock", ["film_colors", "kodak_2383", "technicolor", "kodachrome", "faded_70s", "bleach_bypass", "cross_process"]),
    ("Black & white", ["noir", "silver_mono", "sepia", "daguerreotype"]),
    ("Blockbuster", ["teal_orange", "black_gloss", "chrome", "cyber", "matrix", "neon_night"]),
    ("Light & weather", ["golden_hour", "moonlight", "day_for_night", "amber_haze", "desert", "arctic", "ember"]),
    ("Mood", ["nostalgic_blue", "soft_palette", "pastel", "candy_pink", "lime_jam", "crimson_vigil", "overtime", "horror_green", "dream"]),
    ("Video & print", ["vhs", "camcorder", "infrared", "duotone_ink", "duotone_sunset"]),
]
group_of = {k: g for g, ks in GROUPS for k in ks}
missing = [k for k in pal.LOOKS if k != "natural" and k not in group_of]
if missing:
    raise SystemExit(f"looks with no row: {missing} (add them to GROUPS)")


def clean(v):
    if isinstance(v, tuple):
        return [clean(x) for x in v]
    if isinstance(v, list):
        return [clean(x) for x in v]
    if isinstance(v, float):
        return round(v, 4)
    return v


out = []
for k, lk in pal.LOOKS.items():
    params = {p: clean(v) for p, v in lk.items() if p not in ("name", "words") and clean(v) != clean(pal.Look.NEUTRAL.get(p))}
    out.append({"id": k, "name": lk.name, "group": group_of.get(k, ""), "words": lk.words, "grade": params})

head = ("// Generated by tools/export_palettes.py from valis_fx/lib/palette.py LOOKS: don't edit by hand.\n"
        "// `words` go into the keyframe prompt; `grade` is the look's grading parameters: ValisColorPalette grades the shot with\n"
        "// them, and grade.js previews the same grade in the studio. `group` is the row the look sits in.\n")
body = "export const PALETTE_GROUPS = " + json.dumps([g for g, _ in GROUPS]) + ";\n" + \
       "export const NEUTRAL = " + json.dumps({k: clean(v) for k, v in pal.Look.NEUTRAL.items() if k not in ("name", "words")}) + ";\n" + \
       "export const PALETTES = [\n" + ",\n".join(" " + json.dumps(o, ensure_ascii=False) for o in out) + "\n];\n"
with open(os.path.join(ROOT, "app", "js", "palettes.js"), "w", encoding="utf-8", newline="\n") as f:
    f.write(head + body)
print(f"{len(out)} looks")
